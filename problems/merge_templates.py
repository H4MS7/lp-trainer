#!/usr/bin/env python3
"""Merge all template JSON files into app/src/data/templates.ts and generate catalogue."""

import json
import os
import sys
from pathlib import Path

TEMPLATES_DIR = Path(__file__).parent / "templates"
OUTPUT_TS = Path(__file__).parent.parent / "app" / "src" / "data" / "templates.ts"
CATALOGUE_MD = Path(__file__).parent / "TEMPLATE_CATALOGUE.md"

# Map directory names to display type names
DIR_TO_TYPE = {
    "produktionsproblem": "Produktionsproblem",
    "ressourcenallokation": "Ressourcenallokation",
    "mischungsproblem": "Mischungsproblem",
    "transportproblem": "Transportproblem",
    "investitionsoptimierung": "Investitionsoptimierung",
    "maschinenparametrierung": "Maschinenparametrierung",
    "diaetproblem": "Diätproblem",
    "emissionsoptimierung": "Emissionsoptimierung",
    "schichtplanung": "Schichtplanung",
    "energiemix": "Energiemix",
    "kapazitaetsplanung": "Kapazitätsplanung",
    "medienplanung": "Medienplanung",
    "lagerhaltung": "Lagerhaltung",
    "qualitaetskontrolle": "Qualitätskontrolle",
    "flaechennutzung": "Flächennutzung",
    "wartungsplanung": "Wartungsplanung",
}


def load_all_templates() -> list[dict]:
    """Load all template JSON files, sorted by type then id."""
    templates = []
    for type_dir in sorted(TEMPLATES_DIR.iterdir()):
        if not type_dir.is_dir():
            continue
        for filepath in sorted(type_dir.glob("*.json")):
            with open(filepath) as f:
                t = json.load(f)
            # Ensure typ uses proper display name
            dir_name = type_dir.name
            if dir_name in DIR_TO_TYPE:
                t["typ"] = DIR_TO_TYPE[dir_name]
            templates.append(t)
    return templates


def generate_ts(templates: list[dict]):
    """Generate TypeScript file with typed template array."""
    ts_lines = [
        "// Auto-generated by merge_templates.py — DO NOT EDIT",
        "import type { ProblemTemplate } from '../lib/templateEngine';",
        "",
        f"const ALL_TEMPLATES: ProblemTemplate[] = {json.dumps(templates, ensure_ascii=False, indent=2)};",
        "",
        "export default ALL_TEMPLATES;",
        "",
    ]
    OUTPUT_TS.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_TS.write_text("\n".join(ts_lines), encoding="utf-8")
    print(f"Wrote {OUTPUT_TS} ({len(templates)} templates, {OUTPUT_TS.stat().st_size / 1024:.0f} KB)")


def generate_catalogue(templates: list[dict]):
    """Generate markdown catalogue."""
    lines = [
        "# Template Catalogue",
        "",
        f"**Total: {len(templates)} templates**",
        "",
    ]

    # Group by type
    by_type: dict[str, list[dict]] = {}
    for t in templates:
        typ = t["typ"]
        by_type.setdefault(typ, []).append(t)

    for typ in sorted(by_type.keys()):
        tpls = by_type[typ]
        lines.append(f"## {typ} ({len(tpls)} templates)")
        lines.append("")

        # Sub-group by numVars
        by_vars: dict[int, list[dict]] = {}
        for t in tpls:
            nv = t["numVars"]
            by_vars.setdefault(nv, []).append(t)

        for nv in sorted(by_vars.keys()):
            vtpls = by_vars[nv]
            lines.append(f"### {nv} Variablen ({len(vtpls)} templates)")
            lines.append("")
            for t in vtpls:
                coeff_summary = ", ".join(
                    f"{k}: [{r['min']},{r['max']}]"
                    for k, r in list(t["coefficients"].items())[:4]
                )
                lines.append(f"- **{t['id']}**: {t['titel']} — {coeff_summary}...")
            lines.append("")

    CATALOGUE_MD.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {CATALOGUE_MD}")


def main():
    templates = load_all_templates()
    if not templates:
        print("ERROR: No templates found!")
        sys.exit(1)

    # Summary
    type_counts = {}
    for t in templates:
        type_counts[t["typ"]] = type_counts.get(t["typ"], 0) + 1

    print(f"Loaded {len(templates)} templates:")
    for typ, count in sorted(type_counts.items()):
        print(f"  {typ}: {count}")

    generate_ts(templates)
    generate_catalogue(templates)


if __name__ == "__main__":
    main()
