#!/usr/bin/env python3
"""
Merge all problem batches + exemplars into:
1. all_problems.json (unified JSON)
2. app/src/data/problems.ts (TypeScript export)
3. CATALOGUE.md (all titles listed)
"""
import json
import glob
import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
APP_DIR = os.path.join(SCRIPT_DIR, '..', 'app', 'src', 'data')


def load_json_file(filepath):
    """Load a JSON file and return its contents."""
    with open(filepath, encoding='utf-8') as f:
        return json.load(f)


def deduplicate_by_title(problems):
    """Remove duplicate problems by title, keeping the first occurrence."""
    seen = set()
    unique = []
    for p in problems:
        title = p.get('titel', '')
        if title not in seen:
            seen.add(title)
            unique.append(p)
        else:
            print(f"  Dedup: removing duplicate '{title}'")
    return unique


def write_typescript(problems, output_path):
    """Write problems as a TypeScript export."""
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write('// Auto-generated by merge_and_export.py\n')
        f.write('// eslint-disable-next-line @typescript-eslint/no-explicit-any\n')
        f.write('export const ALL_PROBLEMS = ')
        json.dump(problems, f, ensure_ascii=False, separators=(',', ':'))
        f.write(';\n\nexport default ALL_PROBLEMS;\n')


def write_catalogue(problems, output_path):
    """Write a catalogue of all problem titles grouped by type."""
    type_groups = {}
    for p in problems:
        typ = p.get('typ', 'UNKNOWN')
        if typ not in type_groups:
            type_groups[typ] = []
        type_groups[typ].append(p.get('titel', '???'))

    with open(output_path, 'w', encoding='utf-8') as f:
        f.write('# LP Problem Catalogue\n\n')
        f.write(f'Total: {len(problems)} problems across {len(type_groups)} types\n\n')

        for typ in sorted(type_groups.keys()):
            titles = type_groups[typ]
            f.write(f'## {typ} ({len(titles)})\n\n')
            for i, t in enumerate(sorted(titles), 1):
                f.write(f'{i}. {t}\n')
            f.write('\n')


def main():
    print("Merging LP problem files...")

    # Collect all source files
    batch_files = sorted(glob.glob(os.path.join(SCRIPT_DIR, 'batch_*.json')))
    exemplar_files = sorted(glob.glob(os.path.join(SCRIPT_DIR, 'exemplars', '*.json')))

    all_problems = []

    # Load batch files
    for filepath in batch_files:
        filename = os.path.basename(filepath)
        problems = load_json_file(filepath)
        print(f"  Loaded {len(problems)} from {filename}")
        all_problems.extend(problems)

    # Load exemplar files
    for filepath in exemplar_files:
        filename = os.path.basename(filepath)
        problems = load_json_file(filepath)
        print(f"  Loaded {len(problems)} from exemplars/{filename}")
        all_problems.extend(problems)

    # Deduplicate
    print(f"\n  Total before dedup: {len(all_problems)}")
    all_problems = deduplicate_by_title(all_problems)
    print(f"  Total after dedup: {len(all_problems)}")

    # Type distribution
    type_counts = {}
    for p in all_problems:
        t = p.get('typ', 'UNKNOWN')
        type_counts[t] = type_counts.get(t, 0) + 1

    print(f"\n  Type distribution:")
    for t in sorted(type_counts.keys()):
        print(f"    {t}: {type_counts[t]}")

    # Write outputs
    # 1. all_problems.json
    all_json_path = os.path.join(SCRIPT_DIR, 'all_problems.json')
    with open(all_json_path, 'w', encoding='utf-8') as f:
        json.dump(all_problems, f, indent=2, ensure_ascii=False)
    print(f"\n  Wrote {all_json_path}")

    # 2. problems.ts
    os.makedirs(APP_DIR, exist_ok=True)
    ts_path = os.path.join(APP_DIR, 'problems.ts')
    write_typescript(all_problems, ts_path)
    print(f"  Wrote {ts_path}")

    # 3. CATALOGUE.md
    cat_path = os.path.join(SCRIPT_DIR, 'CATALOGUE.md')
    write_catalogue(all_problems, cat_path)
    print(f"  Wrote {cat_path}")

    print(f"\n{'='*60}")
    print(f"Done! {len(all_problems)} problems merged and exported.")
    print(f"{'='*60}")

    return 0


if __name__ == '__main__':
    sys.exit(main())
